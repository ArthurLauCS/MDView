/** Real Electron checks, isolated from the user's documents and profile. */
const { app, BrowserWindow, dialog, shell } = require('electron')
const fs = require('node:fs/promises')
const path = require('node:path')
const assert = require('node:assert/strict')
const OUT = path.resolve(process.argv[2] || 'design-review/round-links-i18n')
const ROOT = path.resolve(__dirname, '..')
require('node:fs').mkdirSync(OUT, { recursive: true })
app.setPath('userData', path.join(OUT, 'profile'))
app.setPath('documents', OUT)
let confirmResponse = 2
let confirmations = 0
const external = []
shell.openExternal = async url => { external.push(url) }
dialog.showMessageBox = async () => { confirmations++; return { response: confirmResponse } }
require(path.join(ROOT, 'out/main/index.js'))
const wait = ms => new Promise(resolve => setTimeout(resolve, ms))

async function main() {
  for (let i = 0; i < 60 && !BrowserWindow.getAllWindows().length; i++) await wait(100)
  const win = BrowserWindow.getAllWindows()[0]
  win.setSize(1440, 900)
  const run = code => win.webContents.executeJavaScript(code, true).catch(error => { console.error('Renderer expression:', code); throw error })
  const errors = []
  win.webContents.on('console-message', (_e, level, text) => { if (level >= 3) { errors.push(text); console.error(text) } })
  await wait(1200)
  const ctx = 'window.__mdview.editorContext()'
  const settings = patch => run(`window.__mdview.setSettings(${JSON.stringify(patch)})`)
  const shot = async name => fs.writeFile(path.join(OUT, name + '.png'), (await win.webContents.capturePage()).toPNG())
  const sourcePath = path.join(OUT, 'README.md')
  const targetPath = path.join(OUT, 'README.zh-CN.md')
  const spacedPath = path.join(OUT, '中文 文档.md')
  const source = '# Links\n\n[English](README.md) · [简体中文](README.zh-CN.md)\n\n[Web](https://example.com/a_(b)) · <writer@example.com> · https://example.org\n\n[Reference][ref] · [Spaced](<中文 文档.md>) · [Anchor](#target)\n\n[ref]: README.zh-CN.md#中文标题\n[table-ref]: https://example.net/reference\n[image-ref]: data:image/gif;base64,R0lGODlhAQABAIAAAAAAAP///yH5BAEAAAAALAAAAAABAAEAAAIBRAA7\n\n| Link | Value |\n| --- | --- |\n| [Table web](https://example.net) | [Table doc](README.zh-CN.md) |\n| [Table reference][table-ref] | ![reference picture][image-ref] |\n\n[![linked image](data:image/gif;base64,R0lGODlhAQABAIAAAAAAAP///yH5BAEAAAAALAAAAAABAAEAAAIBRAA7)](https://example.com/image)\n\n## Target\n\n**Bold** *italic* ~~strike~~ ==mark== H~2~O x^2^\n\n- [ ] Task\n\n```js\nconst value = 1\n```\n'
  await fs.writeFile(sourcePath, source)
  await fs.writeFile(targetPath, '# Chinese\n\n## 中文标题\n\nTarget document.\n')
  await fs.writeFile(spacedPath, '# Space and encoding\n')
  await settings({ language: 'zh-CN', autoSave: false, historyEnabled: false, sidebarVisible: true, motion: 'off' })
  const openSource = async () => { await run(`window.__mdview.openDocument(${JSON.stringify(sourcePath)})`); await wait(250) }
  const clickLink = async (href, control = true, selector = '[data-md-href]') => {
    const query = `Array.from(document.querySelectorAll(${JSON.stringify(selector)})).find(el => (el.dataset.mdHref ?? el.getAttribute('href')) === ${JSON.stringify(href)})`
    await run(`${query}.scrollIntoView({block:'center'})`)
    await wait(100)
    const point = await run(`(() => { const r=${query}.getBoundingClientRect(); return {x:Math.round(r.left+Math.min(12,r.width/2)),y:Math.round(r.top+r.height/2)} })()`)
    const modifiers = control ? ['control'] : []
    win.webContents.sendInputEvent({ type: 'mouseDown', ...point, button: 'left', clickCount: 1, modifiers })
    win.webContents.sendInputEvent({ type: 'mouseUp', ...point, button: 'left', clickCount: 1, modifiers })
    await wait(350)
  }
  await openSource()
  await clickLink('README.zh-CN.md', false)
  assert.equal(await run(`${ctx}.docPath`), sourcePath)
  await clickLink('README.zh-CN.md')
  assert.equal(await run(`${ctx}.docPath`), targetPath)
  await openSource()
  await clickLink('README.zh-CN.md#%E4%B8%AD%E6%96%87%E6%A0%87%E9%A2%98')
  assert.equal(await run(`${ctx}.docPath`), targetPath)
  assert.equal(await run(`${ctx}.cursor`), '# Chinese\n\n'.length)
  await openSource()
  await clickLink('%E4%B8%AD%E6%96%87%20%E6%96%87%E6%A1%A3.md')
  assert.equal(await run(`${ctx}.docPath`), spacedPath)
  await openSource()
  await clickLink('#target')
  assert.equal(await run(`${ctx}.cursor`), source.indexOf('## Target'))
  for (const href of ['https://example.com/a_(b)', 'mailto:writer@example.com', 'https://example.org']) await clickLink(href)
  await clickLink('https://example.net', true, '.live-table a')
  assert.equal(await run(`document.querySelectorAll('.live-cell-input').length`), 0)
  await clickLink('https://example.net/reference', true, '.live-table a')
  assert.equal(await run(`document.querySelector('.live-table img').complete && document.querySelector('.live-table img').naturalWidth > 0`), true)
  await clickLink('https://example.com/image')
  assert.deepEqual(external, ['https://example.com/a_(b)', 'mailto:writer@example.com', 'https://example.org', 'https://example.net', 'https://example.net/reference', 'https://example.com/image'])
  await clickLink('README.zh-CN.md', true, '.live-table a')
  assert.equal(await run(`${ctx}.docPath`), targetPath)
  await openSource()
  await settings({ readOnly: true })
  await clickLink('README.zh-CN.md')
  assert.equal(await run(`${ctx}.docPath`), targetPath)
  await settings({ readOnly: false })
  await openSource()
  await run(`${ctx}.replace(${ctx}.source.length,${ctx}.source.length,'Unsaved draft')`)
  await wait(100)
  await clickLink('README.zh-CN.md')
  assert.equal(confirmations, 1)
  assert.equal(await run(`${ctx}.docPath`), sourcePath)
  assert.ok((await run(`${ctx}.source`)).endsWith('Unsaved draft'))
  await run(`window.__editorBefore=document.querySelector('.cm-editor'); ${ctx}.select(2,2)`)
  await settings({ language: 'en' })
  await wait(250)
  assert.equal(await run(`document.documentElement.lang`), 'en')
  assert.equal(await run(`window.__editorBefore===document.querySelector('.cm-editor')`), true)
  assert.equal(await run(`${ctx}.cursor`), 2)
  assert.ok((await run(`${ctx}.source`)).endsWith('Unsaved draft'))
  await run(`${ctx}.undo()`)
  await wait(150)
  assert.equal(await run(`${ctx}.source`), source)
  assert.equal(await run(`document.title`), 'MDWisp')
  await run(`document.querySelector('.cm-scroller').scrollTop=0`)
  await wait(100)
  await shot('01-editor-en-dark')
  await run(`${ctx}.replace(0,0,'#\\n\\n')`)
  await wait(100)
  assert.equal(await run(`document.querySelector('.outline__label').textContent`), 'Untitled heading')
  await run(`${ctx}.undo(); ${ctx}.select(${source.indexOf('[Table web]') + 2},${source.indexOf('[Table web]') + 2})`)
  await wait(150)
  assert.doesNotMatch(await run(`document.querySelector('.ttable').textContent`), /\p{Script=Han}|undefined/u)
  await shot('04-table-tools-en')
  await run(`${ctx}.select(2,2)`)
  await run(`window.__mdview.openPanel('settings')`)
  await wait(150)
  const noChinese = async selector => assert.doesNotMatch(await run(`document.querySelector(${JSON.stringify(selector)}).textContent`), /\p{Script=Han}/u)
  for (const label of ['Appearance & fonts', 'Documents & saving', 'Editor', 'Images', 'Keyboard shortcuts']) {
    await run(`Array.from(document.querySelectorAll('.settings__tab')).find(el=>el.textContent===${JSON.stringify(label)}).click()`)
    await wait(100)
    // The bilingual language selector deliberately names Simplified Chinese in Chinese.
    const text = await run(`document.querySelector('.settings').textContent.replace('简体中文','')`)
    assert.doesNotMatch(text, /\p{Script=Han}/u, label)
    await shot('settings-' + label.replace(/[^a-z]+/gi, '-').toLowerCase())
  }
  await run(`Array.from(document.querySelectorAll('.settings__tab')).find(el=>el.textContent==='Appearance & fonts').click()`)
  await settings({ theme: 'light' })
  await wait(100)
  await shot('02-settings-en-light')
  await settings({ language: 'zh-CN', theme: 'dark' })
  await wait(100)
  assert.equal(await run(`document.querySelector('.panel__title').textContent`), '设置')
  await shot('03-settings-zh-dark')
  await settings({ language: 'en' })
  for (const panel of ['help','export','shortcuts','palette']) {
    await run(`window.__mdview.openPanel(${JSON.stringify(panel)})`)
    await wait(250)
    await noChinese(panel === 'palette' ? '.palette' : '.panel')
  }
  await run(`window.__mdview.closePanel()`)
  await run(`${ctx}.save()`)
  await wait(150)
  win.webContents.reload()
  await wait(1200)
  assert.equal(await run(`document.documentElement.lang`), 'en')
  assert.equal(JSON.parse(await fs.readFile(path.join(OUT, 'profile', 'settings.json'), 'utf8')).language, 'en')
  assert.equal(await run(`${ctx}.source`), source)
  assert.deepEqual(errors, [])
  console.log('PASS: native Ctrl+click, relative/reference/table/image links, URLs/mail, anchors, encoding, read-only, unsaved cancellation, live language switch, editor identity/undo, all settings/panels, persistence')
  app.exit(0)
}
app.whenReady().then(() => main().catch(error => { console.error(error); app.exit(1) }))
